#!/usr/bin/env python3
"""V5.3.0 R11 (game build 1090142): generate src/urt_build_table.h from tools/port/port_map_1090142.tsv.
Each row: Patch 5.01 (build 1048522) RVA -> build 1090142 RVA, how it was found and what uses it.
Usage: gen_build_table.py [--check]   (--check: fail if the header is out of date)"""
import pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
TSV = ROOT / 'tools/port/port_map_1090142.tsv'
OUT = ROOT / 'src/urt_build_table.h'

def render():
    rows = []
    for l in TSV.read_text().splitlines():
        if not l.strip() or l.startswith('#'): continue
        p = l.split('\t')
        old, new = int(p[0], 16), int(p[1], 16)
        rows.append((old, new, p[2], p[3]))
    rows.sort()
    olds = [r[0] for r in rows]
    if len(set(olds)) != len(olds): raise SystemExit('duplicate old RVA')
    out = ['/* GENERATED by tools/port/gen_build_table.py from tools/port/port_map_1090142.tsv - do not edit. */',
           '#ifndef URT_BUILD_TABLE_H', '#define URT_BUILD_TABLE_H',
           '/* Patch 5.01 build 1048522 RVA -> game build 1090142 RVA (sorted by the first column). */',
           '#define URT_BUILD_MAP_COUNT %du' % len(rows),
           'static const uint32_t kUrtBuildMap1090142[URT_BUILD_MAP_COUNT][2]={']
    for old, new, kind, user in rows:
        out.append('  {0x%07xu,0x%07xu}, /* %s: %s */' % (old, new, kind, user.replace('*/', '')))
    out += ['};', '#endif', '']
    return '\n'.join(out)

if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print('urt_build_table.h', 'up to date' if ok else 'OUT OF DATE'); sys.exit(0 if ok else 1)
    OUT.write_text(text); print('wrote', OUT)
