#!/usr/bin/env python3
"""V5.3.0 PRIVATE locale step (runs after build_v53_locales.py, before build_v53_dev2_strings.py).
Adds only new keys: the row titles (bare and option_ keys) (English in every language, the V5.2.0 row-name convention), their
descriptions (generated by tools/v53_dev/tooltips_dev2.py, 18 languages) and one value label ("15 m").
IDs 1194783000 + index (collision-checked). No existing string is changed here."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools')); sys.path.insert(0, str(ROOT / 'tools' / 'v53_dev')); sys.path.insert(0, str(ROOT / 'tools' / 'v52_selected'))
import rc1_w3codec as C
import tooltips_dev2 as T
import spec as S
import tip_core_e as E
BASE_ID = 1194783000
ROWS = [r for r in S.ROWS_V530 if r.get('menu', True)]
def h(s):
    v = 0
    for c in s.lower():
        raw = c.encode('utf-16le')
        for i in range(0, len(raw), 2): v = (31 * v + int.from_bytes(raw[i:i + 2], 'little')) & 0xffffffff
    return v
def main():
    docs = {l: C.decode((ROOT / 'build/loc' / f'{l}.w3strings').read_bytes(), l) for l in T.LANGS}
    def loc(l, k):
        if k in E.LABELS: return E.LABELS[k][l]   # rev2 labels are added by this step
        d = docs[l]; i = dict(d.block2)[h(k)]
        return next(b[3] for b in d.blocks if b[0] == i)
    sub = {cid: T.SPEC[cid] for cid in [r['id'] for r in ROWS]}
    full, T.SPEC = T.SPEC, sub                 # assemble only the new descriptions
    try: tips = T.tooltips(loc)
    finally: T.SPEC = full
    for l in T.LANGS:
        recs = {r['id'].lower(): r['label'] for r in ROWS}
        # rev2: the game resolves a Var title as "option_" + displayName (rev1 added only the bare key, so the
        # titles showed as raw identifiers in game); both keys carry the same English title (row-name convention).
        recs.update({'option_' + r['id'].lower(): r['label'] for r in ROWS})
        recs['urt530_m15'] = '15 m'
        # R6: EXPERIMENTAL heading (English in every language, like "Frame Generation"); padded like every URT heading
        recs['urt531_sep_exp'] = recs['option_urt531_sep_exp'] = ' EXPERIMENTAL\xa0'
        recs.update({k: v[l] for k, v in E.LABELS.items()})   # rev2 value labels (Fast Trace / Fast Build)
        recs.update(tips[l])
        d = docs[l]; ids = dict(d.block2); used = {b[0] for b in d.blocks}
        for n, k in enumerate(sorted(recs)):
            if h(k) in ids: raise SystemExit('V5.3.0: key already exists: ' + k)
            nid = BASE_ID + n
            if nid in used: raise SystemExit('V5.3.0: ID collision ' + k)
            d.blocks.append([nid, 0, 0, recs[k]]); d.block2.append([h(k), nid])
        raw = C.encode(d, l); assert C.encode(C.decode(raw, l), l) == raw
        (ROOT / 'build/loc' / f'{l}.w3strings').write_bytes(raw)
    print('PASS V5.3.0 locales: 18 languages; %d keys added per language (titles, descriptions, 1 value label)' % len(recs))
if __name__ == '__main__':
    main()
