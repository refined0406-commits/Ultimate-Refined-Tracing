#!/usr/bin/env python3
"""tools/v52_selected/spec.py -> src/urt_gfx_table.h / src/urt_gfx_table.c (generated, committed).
`gen_table.py --check` fails if the committed files differ from the spec."""
import sys, struct
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec as S

SCOPE = {'ALL': 'URT_GX_ALL', 'RT': 'URT_GX_RT', 'PT': 'URT_GX_PT', 'RTPT': 'URT_GX_RTPT'}
KIND = {'b': 'URT_GX_BOOL', 'i': 'URT_GX_INT', 'f': 'URT_GX_FLOAT'}
def raw(kind, v):
    if kind == 'f':
        return struct.unpack('<I', struct.pack('<f', float(v)))[0]
    v = int(v)
    assert -2**31 <= v < 2**32, v
    return v & 0xffffffff
def special(r):
    if r['id'] == 'URTX_RTAnimatedBVH': return 'URT_GX_SPECIAL_FASTTRACE'
    if r['id'] == 'URTX_FGMenuResources': return 'URT_GX_SPECIAL_FG'
    if r['id'] in ('URTX_PTDiffuseCoverage', 'URTX_ExpPTSunShadowCoverage', 'URTX_ExpPTLocalShadowCoverage'): return 'URT_GX_SPECIAL_BOUNCE'
    return 'URT_GX_SPECIAL_NONE'
MAXV = max(len(r['vals']) for r in S.ROWS)

def render():
    h = ['/* GENERATED by tools/v52_selected/gen_table.py from tools/v52_selected/spec.py - do not edit. */',
         '#ifndef URT_GFX_TABLE_H', '#define URT_GFX_TABLE_H', '#include <stdint.h>',
         '#define URT_GX_COUNT %du' % len(S.ROWS), '#define URT_GX_MAXVALS %du' % MAXV,
         'enum { URT_GX_BOOL = 0, URT_GX_INT = 1, URT_GX_FLOAT = 2 };',
         'enum { URT_GX_ALL = 0, URT_GX_RT = 1, URT_GX_PT = 2, URT_GX_RTPT = 3 };',
         'enum { URT_GX_SPECIAL_NONE = 0, URT_GX_SPECIAL_FASTTRACE = 1, URT_GX_SPECIAL_FG = 2, URT_GX_SPECIAL_PTLIGHTS = 3, URT_GX_SPECIAL_FOLIAGE = 4, URT_GX_SPECIAL_BOUNCE = 5 };',
         'enum { URT_GX_STAGE_LIVE = 0, URT_GX_STAGE_STARTUP = 1, URT_GX_STAGE_BOOT = 2 };',
         '#define URT_GX_NO_LEAD 0xffu',
         'typedef struct {',
         '  const char *key;        /* menu Var id in [URTExtended] */',
         '  const char *cvar;       /* engine variable ("" for special controls) */',
         '  const char *category;   /* real descriptor category (+48) */',
         '  uint32_t flags, def;    /* descriptor flags (+8) and registered default (+24) */',
         '  uint32_t rva;           /* pinned value RVA on the exact Patch 5.01 executable */',
         '  uint8_t kind, scope, special, nvals;',
         '  uint8_t stage;          /* 0 = live (renderer scope), 1 = startup (read once when ray tracing initialises), 2 = boot (written once before the renderer, kept all session) */',
         '  uint8_t lead;           /* URT_GX_NO_LEAD, or the row whose option index this hidden row follows (no menu key) */',
         '  uint32_t vals[URT_GX_MAXVALS]; /* raw value of option i+1 (option 0 = Native) */',
         '} UrtGxDef;',
         'extern const UrtGxDef urt_gx_defs[URT_GX_COUNT];']
    for i, r in enumerate(S.ROWS):
        h.append('#define URT_GX_IX_%s %du' % (r['id'][5:].upper(), i))
    h += ['#endif', '']
    c = ['/* GENERATED by tools/v52_selected/gen_table.py from tools/v52_selected/spec.py - do not edit. */',
         '#include "urt_gfx_table.h"', 'const UrtGxDef urt_gx_defs[URT_GX_COUNT] = {']
    for r in S.ROWS:
        vals = ', '.join('0x%08xu' % raw(r['kind'], v) for v in r['vals'])
        st = {'startup': 'URT_GX_STAGE_STARTUP', 'boot': 'URT_GX_STAGE_BOOT'}.get(r.get('stage'), 'URT_GX_STAGE_LIVE')
        lead = ('%du' % [x['id'] for x in S.ROWS].index(r['follows'])) if r.get('follows') else 'URT_GX_NO_LEAD'
        c.append('  {"%s", "%s", "%s", 0x%xu, 0x%08xu, 0x%xu, %s, %s, %s, %du, %s, %s, {%s}},  /* %s */' % (
            r['id'], r['cvar'], r['cat'], r['flags'], r['dflt'] & 0xffffffff, r['rva'], KIND[r['kind']],
            SCOPE[r['scope']], special(r), len(r['vals']), st, lead, vals,
            'V5.3.0 private' if r in S.ROWS_V530 else ('V5.3 dev' if 'stage' in r else 'selected')))
    c += ['};', '']
    return '\n'.join(h), '\n'.join(c)

if __name__ == '__main__':
    hh, cc = render()
    ph, pc = ROOT / 'src/urt_gfx_table.h', ROOT / 'src/urt_gfx_table.c'
    if '--check' in sys.argv:
        ok = ph.read_text() == hh and pc.read_text() == cc
        print('PASS generated table matches spec' if ok else 'FAIL generated table differs from spec'); sys.exit(0 if ok else 1)
    ph.write_text(hh); pc.write_text(cc)
    print('wrote', len(S.ROWS), 'rows; max values', MAXV)
